#!/usr/bin/env python3
"""Генерирует карту школы для HE WILL COME.

Комнаты описаны прямоугольниками в тайлах (1 тайл = 4 стада), скрипт растеризует
их в текстовую схему, проверяет проходимость и пишет src/server/MapData.lua.

Легенда:
  #  стена           .  пол комнаты        ,  пол коридора
  ' '(пробел) трава  =  асфальт            F  забор           T  дерево
  W  окно (стена со стеклом)               X  ворота выхода (в заборе)
  P  спавн игрока    M  спавн монстра     D  дверной проём (перемычка сверху)
  L  шкафчик (спрятаться)                  B  парта/рюкзак (обыскать)
"""

import pathlib
import collections

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "roblox-he-will-come" / "src" / "server" / "MapData.lua"

W, H = 64, 48
grid = [[" "] * W for _ in range(H)]


def fill(c1, r1, c2, r2, ch):
    for r in range(r1, r2 + 1):
        for c in range(c1, c2 + 1):
            grid[r][c] = ch


def put(c, r, ch):
    grid[r][c] = ch


# --- здание: сплошной блок стен, из которого вырезаем комнаты -----------------
BX1, BY1, BX2, BY2 = 8, 8, 55, 39
fill(BX1, BY1, BX2, BY2, "#")

# коридоры
fill(9, 22, 54, 24, ",")   # главный, восток-запад
fill(21, 9, 22, 38, ",")   # западный, север-юг
fill(41, 9, 42, 38, ",")   # восточный, север-юг

ROOMS = {
    # имя: (c1, r1, c2, r2)
    "Библиотека": (9, 9, 19, 20),
    "Класс A": (24, 9, 31, 14),
    "Класс B": (24, 16, 31, 20),
    "Класс C": (33, 9, 39, 14),
    "Класс D": (33, 16, 39, 20),
    "Спортзал": (44, 9, 54, 20),
    "Столовая": (9, 26, 19, 38),
    "Учительская": (24, 26, 28, 31),
    "Туалеты": (30, 26, 33, 31),
    "Кладовка": (35, 26, 39, 31),
    "Холл": (24, 33, 39, 38),
    "Мастерская": (44, 26, 54, 31),
    "Котельная": (44, 33, 54, 38),
}
for name, (c1, r1, c2, r2) in ROOMS.items():
    fill(c1, r1, c2, r2, ".")

# двери: вырезаем 2 тайла (8 стадов) в стене
DOORS = [
    (20, 14), (20, 15),        # Библиотека -> западный коридор
    (12, 21), (13, 21),        # Библиотека -> главный коридор
    (23, 11), (23, 12),        # Класс A -> западный коридор
    (27, 21), (28, 21),        # Класс B -> главный коридор
    (40, 11), (40, 12),        # Класс C -> восточный коридор
    (35, 21), (36, 21),        # Класс D -> главный коридор
    (43, 14), (43, 15),        # Спортзал -> восточный коридор
    (48, 21), (49, 21),        # Спортзал -> главный коридор
    (13, 25), (14, 25),        # Столовая -> главный коридор
    (20, 30), (20, 31),        # Столовая -> западный коридор
    (25, 25), (26, 25),        # Учительская -> главный
    (31, 25), (32, 25),        # Туалеты -> главный
    (37, 25), (38, 25),        # Кладовка -> главный
    (23, 35), (23, 36),        # Холл -> западный коридор
    (40, 35), (40, 36),        # Холл -> восточный коридор
    (31, 39), (32, 39),        # Холл -> двор (главный вход)
    (43, 28), (43, 29),        # Мастерская -> восточный коридор
    (43, 35), (43, 36),        # Котельная -> восточный коридор
    (29, 17), (29, 18),        # Класс B <-> ... нет, это стена между B и D? (см. ниже)
]
# проход Класс B -> Класс D через стену col 32 (срезаем путь, чтобы было где петлять)
DOORS = [d for d in DOORS if d not in [(29, 17), (29, 18)]] + [(32, 18), (32, 19)]
for c, r in DOORS:
    put(c, r, "D")

# окна во внешней стене: каждый третий тайл, кроме углов и дверей
for c in range(BX1 + 1, BX2):
    for r in (BY1, BY2):
        if grid[r][c] == "#" and c % 3 == 1 and grid[r + (1 if r == BY1 else -1)][c] in ".,":
            put(c, r, "W")
for r in range(BY1 + 1, BY2):
    for c in (BX1, BX2):
        if grid[r][c] == "#" and r % 3 == 1 and grid[r][c + (1 if c == BX1 else -1)] in ".,":
            put(c, r, "W")

# --- двор ---------------------------------------------------------------------
fill(1, 1, 62, 1, "F")
fill(1, 46, 62, 46, "F")
fill(1, 1, 1, 46, "F")
fill(62, 1, 62, 46, "F")
# ворота в южном заборе
put(31, 46, "X")
put(32, 46, "X")
# асфальт от входа к воротам и вокруг здания
fill(31, 40, 32, 45, "=")
fill(7, 40, 56, 41, "=")
fill(7, 6, 56, 7, "=")
TREES = [(3, 3), (5, 10), (3, 20), (4, 30), (3, 40), (60, 4), (59, 12), (60, 22), (59, 33), (60, 43),
         (12, 3), (25, 3), (40, 3), (52, 3), (12, 44), (22, 44), (45, 44), (55, 44), (18, 43), (48, 43)]
for c, r in TREES:
    put(c, r, "T")

# --- объекты -------------------------------------------------------------------
# спавн игроков в холле
for c, r in [(26, 36), (27, 36), (36, 36), (37, 36)]:
    put(c, r, "P")
# монстр в котельной
put(50, 36, "M")

# шкафчики (спрятаться) - у стен комнат
LOCKERS = [
    (9, 12), (9, 17),                 # библиотека
    (24, 9), (31, 16),                # классы A, B
    (33, 9), (39, 16),                # классы C, D
    (44, 9), (54, 9), (44, 20),       # спортзал
    (9, 28), (19, 28), (9, 36),       # столовая
    (24, 33), (39, 33),               # холл
    (28, 26), (35, 31),               # учительская, кладовка
    (44, 26), (54, 31),               # мастерская
    (44, 38),                         # котельная
]
for c, r in LOCKERS:
    put(c, r, "L")

# парты и рюкзаки (обыскать) - в них могут быть ключи
SEARCH = []
for c1, r1 in [(24, 9), (24, 16), (33, 9), (33, 16)]:   # четыре класса
    for dc in (1, 3, 5):
        for dr in (1, 3):
            SEARCH.append((c1 + dc, r1 + dr))
SEARCH += [(11, 11), (14, 11), (11, 15), (14, 15), (17, 18)]     # библиотека
SEARCH += [(11, 30), (14, 30), (11, 34), (14, 34), (17, 32)]     # столовая
SEARCH += [(25, 28), (27, 28)]                                   # учительская
SEARCH += [(36, 28), (38, 28)]                                   # кладовка
SEARCH += [(46, 28), (49, 28), (52, 28)]                         # мастерская
SEARCH += [(47, 12), (51, 12), (47, 17), (51, 17)]               # спортзал
SEARCH += [(30, 34), (33, 34)]                                   # холл
for c, r in SEARCH:
    assert grid[r][c] == ".", f"обыскиваемый объект не на полу: {(c, r)} = {grid[r][c]!r}"
    put(c, r, "B")

# --- проверки -------------------------------------------------------------------
WALKABLE = set(".,= PMBLXD")   # по чему можно ходить


def neighbors(c, r):
    for dc, dr in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        nc, nr = c + dc, r + dr
        if 0 <= nc < W and 0 <= nr < H:
            yield nc, nr


def reachable(start):
    seen = {start}
    queue = collections.deque([start])
    while queue:
        c, r = queue.popleft()
        for n in neighbors(c, r):
            if n not in seen and grid[n[1]][n[0]] in WALKABLE:
                seen.add(n)
                queue.append(n)
    return seen


spawns = [(c, r) for r in range(H) for c in range(W) if grid[r][c] == "P"]
reach = reachable(spawns[0])
problems = []
for r in range(H):
    for c in range(W):
        ch = grid[r][c]
        if ch in "PMBLX" and (c, r) not in reach:
            problems.append((ch, c, r))
for name, (c1, r1, c2, r2) in ROOMS.items():
    if (c1, r1) not in reach:
        problems.append(("room " + name, c1, r1))
assert not problems, "недостижимо: %s" % problems
assert len(spawns) == 4
assert sum(row.count("M") for row in grid) == 1
assert sum(row.count("B") for row in grid) >= 30

text = "\n".join("".join(row) for row in grid)
lua = '--!nonstrict\n-- Сгенерировано tools/gen_school_map.py - правь генератор, не этот файл.\n'
lua += '-- 1 символ = 4 стада. Легенда в MapBuilder.lua.\n\nlocal MapData = {}\n\n'
lua += 'MapData.TileSize = 4\n\nMapData.Grid = [[\n' + text + '\n]]\n\n'
lua += 'MapData.Rooms = {\n'
for name, (c1, r1, c2, r2) in ROOMS.items():
    lua += '\t{ name = "%s", c1 = %d, r1 = %d, c2 = %d, r2 = %d },\n' % (name, c1, r1, c2, r2)
lua += '}\n\nreturn MapData\n'
OUT.write_text(lua, encoding="utf-8")

print(text)
print()
print("размер: %dx%d тайлов = %dx%d стадов" % (W, H, W * 4, H * 4))
print("обыскиваемых: %d, шкафчиков: %d, деревьев: %d" % (
    sum(row.count("B") for row in grid), sum(row.count("L") for row in grid), len(TREES)))
print("записано:", OUT)
