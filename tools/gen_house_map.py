#!/usr/bin/env python3
"""Генерирует карту огромного дома для HE WILL COME.

1 тайл = 6 стадов. Комнаты - прямоугольники, двери и щели - координаты в стене.
Скрипт проверяет, что всё достижимо от спавна, и пишет src/server/MapData.lua.

Легенда:
  #  стена           .  пол комнаты      ,  пол коридора     D  дверной проём
  V  ЩЕЛЬ в стене: снизу дыра 3.5 стада - пролезть можно только подкатом, киллер обходит
  L  шкаф (спрятаться)      K  место, где может лежать ключ
  t  стол   b  кровать   s  стеллаж   c  ящик   (мебель, за ней ломается обзор)
  P  спавн игрока    M  спавн киллера    X  дверь выхода (во внешней стене)
  ' '  трава снаружи
"""

import collections
import pathlib
import random

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "roblox-he-will-come" / "src" / "server" / "MapData.lua"

W, H = 64, 48
grid = [[" "] * W for _ in range(H)]
rng = random.Random(7)


def fill(c1, r1, c2, r2, ch):
    for r in range(r1, r2 + 1):
        for c in range(c1, c2 + 1):
            grid[r][c] = ch


def put(c, r, ch):
    grid[r][c] = ch


# --- здание: всё стены, вырезаем комнаты и коридоры ---------------------------
fill(0, 0, 63, 45, "#")

# коридоры шириной 3 тайла = 18 стадов
fill(1, 14, 62, 16, ",")     # верхний горизонтальный
fill(1, 31, 62, 33, ",")     # нижний горизонтальный
fill(20, 1, 22, 44, ",")     # левый вертикальный
fill(41, 1, 43, 44, ",")     # правый вертикальный

ROOMS = {
    "Холл": (24, 18, 39, 29),          # 16x12 тайлов = 96x72 стадов
    "Гостиная": (1, 1, 9, 12),
    "Кабинет": (11, 1, 18, 12),
    "Детская": (24, 1, 39, 6),
    "Спальня": (24, 8, 39, 12),
    "Кухня": (45, 1, 53, 12),
    "Кладовая": (55, 1, 62, 12),
    "Бальный зал": (1, 18, 18, 29),    # 18x12 = 108x72
    "Библиотека": (45, 18, 62, 22),
    "Оранжерея": (45, 24, 62, 29),
    "Прачечная": (1, 35, 9, 44),
    "Подвал": (11, 35, 18, 44),
    "Вестибюль": (24, 35, 39, 44),
    "Гараж": (45, 35, 53, 44),
    "Мастерская": (55, 35, 62, 44),
}
for name, (c1, r1, c2, r2) in ROOMS.items():
    fill(c1, r1, c2, r2, ".")

# двери (2 тайла = 12 стадов), холл - двойные (4 тайла = 24 стада)
DOORS = [
    (4, 13), (5, 13),          # Гостиная -> верхний коридор
    (19, 6), (19, 7),          # Кабинет -> левый коридор
    (30, 7), (31, 7),          # Детская <-> Спальня
    (23, 3), (23, 4),          # Детская -> левый коридор
    (35, 13), (36, 13),        # Спальня -> верхний коридор
    (44, 4), (44, 5),          # Кухня -> правый коридор
    (48, 13), (49, 13),        # Кухня -> верхний коридор
    (54, 8), (54, 9),          # Кухня <-> Кладовая
    (58, 13), (59, 13),        # Кладовая -> верхний коридор
    (19, 23), (19, 24),        # Бальный зал -> левый коридор
    (8, 17), (9, 17),          # Бальный зал -> верхний коридор
    (10, 30), (11, 30),        # Бальный зал -> нижний коридор
    (23, 22), (23, 23), (23, 24), (23, 25),   # Холл <- левый коридор (двойная)
    (40, 22), (40, 23), (40, 24), (40, 25),   # Холл -> правый коридор (двойная)
    (30, 17), (31, 17), (32, 17), (33, 17),   # Холл -> верхний коридор (двойная)
    (30, 30), (31, 30), (32, 30), (33, 30),   # Холл -> нижний коридор (двойная)
    (44, 19), (44, 20),        # Библиотека -> правый коридор
    (52, 23), (53, 23),        # Библиотека <-> Оранжерея
    (58, 30), (59, 30),        # Оранжерея -> нижний коридор
    (44, 27), (44, 28),        # Оранжерея -> правый коридор
    (4, 34), (5, 34),          # Прачечная -> нижний коридор
    (19, 38), (19, 39),        # Подвал -> левый коридор
    (14, 34), (15, 34),        # Подвал -> нижний коридор
    (30, 34), (31, 34), (32, 34), (33, 34),   # Вестибюль <- нижний коридор (двойная)
    (23, 40), (23, 41),        # Вестибюль <- левый коридор
    (40, 40), (40, 41),        # Вестибюль -> правый коридор
    (48, 34), (49, 34),        # Гараж -> нижний коридор
    (54, 38), (54, 39),        # Гараж <-> Мастерская
    (58, 34), (59, 34),        # Мастерская -> нижний коридор
]
for c, r in DOORS:
    assert grid[r][c] == "#", f"дверь не в стене: {(c, r)}"
    put(c, r, "D")

# ЩЕЛИ: короткие пути, доступные только подкатом
SLITS = [
    (10, 4),            # Гостиная <-> Кабинет
    (13, 13),           # Кабинет -> верхний коридор
    (27, 13),           # Спальня -> верхний коридор (второй выход)
    (44, 10),           # Кухня -> правый коридор
    (54, 3),            # Кухня <-> Кладовая
    (2, 17),            # Бальный зал -> верхний коридор
    (17, 30),           # Бальный зал -> нижний коридор
    (23, 19),           # Холл <- левый коридор
    (40, 28),           # Холл -> правый коридор
    (26, 17), (37, 30), # Холл: ещё две щели
    (44, 21),           # Библиотека -> правый коридор
    (47, 23),           # Библиотека <-> Оранжерея
    (10, 40),           # Прачечная <-> Подвал
    (19, 42),           # Подвал -> левый коридор
    (26, 34),           # Вестибюль <- нижний коридор
    (44, 43),           # Гараж <- правый коридор
    (54, 36),           # Гараж <-> Мастерская
    (7, 34),            # Прачечная -> нижний коридор (вторая)
]
for c, r in SLITS:
    assert grid[r][c] == "#", f"щель не в стене: {(c, r)}"
    put(c, r, "V")

# выход: дверь во внешней стене под вестибюлем, снаружи трава
put(31, 45, "X")
put(32, 45, "X")

# --- объекты -------------------------------------------------------------------
for c, r in [(30, 2), (31, 2), (32, 2), (33, 2)]:      # спавн в детской (далеко от выхода)
    put(c, r, "P")
put(31, 23, "M")                                       # киллер просыпается в центре холла

LOCKERS = [
    (1, 1), (9, 12), (11, 1), (18, 12), (24, 1), (39, 6), (24, 8), (39, 12),
    (45, 1), (53, 12), (55, 1), (62, 12),
    (1, 18), (18, 18), (1, 29), (18, 29), (9, 23),
    (24, 18), (39, 18), (24, 29), (39, 29), (31, 18), (31, 29),
    (45, 18), (62, 22), (45, 24), (62, 29),
    (1, 35), (9, 44), (11, 35), (18, 44), (24, 35), (39, 35), (24, 44), (39, 44),
    (45, 35), (53, 44), (55, 35), (62, 44),
    # в коридорах, у стен
    (1, 14), (12, 16), (30, 14), (50, 16), (62, 14),
    (1, 31), (12, 33), (50, 31), (62, 33),
    (20, 3), (22, 10), (20, 20), (22, 27), (20, 37), (22, 43),
    (41, 3), (43, 10), (41, 20), (43, 27), (41, 37), (43, 43),
]
for c, r in LOCKERS:
    assert grid[r][c] in ".,", f"шкаф не на полу: {(c, r)} = {grid[r][c]!r}"
    put(c, r, "L")

KEY_SPOTS = [
    (5, 6), (15, 6), (48, 6), (58, 6), (9, 21), (5, 27), (53, 20), (49, 27),
    (5, 40), (15, 40), (49, 40), (58, 40), (27, 21), (36, 27),
]
for c, r in KEY_SPOTS:
    assert grid[r][c] == ".", f"ключ не на полу: {(c, r)}"
    put(c, r, "K")

# мебель: случайно внутри комнат, не у дверей, не на объектах
FURNITURE = "tbsc"
for name, (c1, r1, c2, r2) in ROOMS.items():
    area = (c2 - c1 + 1) * (r2 - r1 + 1)
    count = max(3, area // 12)
    tries = 0
    while count > 0 and tries < 200:
        tries += 1
        c = rng.randint(c1 + 1, c2 - 1)
        r = rng.randint(r1 + 1, r2 - 1)
        if grid[r][c] != ".":
            continue
        # не ставим мебель вплотную к дверям и щелям
        near_door = any(grid[r + dr][c + dc] in "DV" for dc in (-2, -1, 0, 1, 2) for dr in (-2, -1, 0, 1, 2)
                        if 0 <= r + dr < H and 0 <= c + dc < W)
        if near_door:
            continue
        put(c, r, rng.choice(FURNITURE))
        count -= 1

# --- проверки -------------------------------------------------------------------
WALK_ALL = set(".,DVPMKLXtbsc ")      # игрок (щели проходимы подкатом)
WALK_KILLER = set(".,DPMKLXtbsc ")    # киллер (щели непроходимы)


def reachable(start, walkable):
    seen = {start}
    queue = collections.deque([start])
    while queue:
        c, r = queue.popleft()
        for dc, dr in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            n = (c + dc, r + dr)
            if 0 <= n[0] < W and 0 <= n[1] < H and n not in seen and grid[n[1]][n[0]] in walkable:
                seen.add(n)
                queue.append(n)
    return seen


spawns = [(c, r) for r in range(H) for c in range(W) if grid[r][c] == "P"]
monster = [(c, r) for r in range(H) for c in range(W) if grid[r][c] == "M"][0]
player_reach = reachable(spawns[0], WALK_ALL)
killer_reach = reachable(monster, WALK_KILLER)

problems = []
for r in range(H):
    for c in range(W):
        ch = grid[r][c]
        if ch in "PMKLX" and (c, r) not in player_reach:
            problems.append(("игрок не дойдёт", ch, c, r))
        if ch in "PKLX" and (c, r) not in killer_reach:
            problems.append(("киллер не дойдёт (без щелей)", ch, c, r))
for name, (c1, r1, c2, r2) in ROOMS.items():
    if (c1, r1) not in killer_reach:
        problems.append(("комната недоступна киллеру", name, c1, r1))
assert not problems, "\n".join(map(str, problems))
assert len(spawns) == 4

text = "\n".join("".join(row) for row in grid)
lua = "--!nonstrict\n-- Сгенерировано tools/gen_house_map.py - правь генератор, не этот файл.\n"
lua += "-- 1 символ = 6 стадов. Легенда в MapBuilder.lua.\n\nlocal MapData = {}\n\n"
lua += "MapData.TileSize = 6\n\nMapData.Grid = [[\n" + text + "\n]]\n\n"
lua += "MapData.Rooms = {\n"
for name, (c1, r1, c2, r2) in ROOMS.items():
    lua += '\t{ name = "%s", c1 = %d, r1 = %d, c2 = %d, r2 = %d },\n' % (name, c1, r1, c2, r2)
lua += "}\n\nreturn MapData\n"
OUT.write_text(lua, encoding="utf-8")

print(text)
print()
print("размер: %dx%d тайлов = %dx%d стадов" % (W, H, W * 6, H * 6))
print("шкафов: %d, мест под ключи: %d, щелей: %d, мебели: %d" % (
    sum(row.count("L") for row in grid), sum(row.count("K") for row in grid),
    sum(row.count("V") for row in grid), sum(sum(row.count(f) for f in FURNITURE) for row in grid)))
